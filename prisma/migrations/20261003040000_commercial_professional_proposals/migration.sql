-- CE-9 Professional RFP / Proposal workflow
CREATE TABLE professional_proposals (
  id CHAR(36) NOT NULL,
  workspace_id CHAR(36) NOT NULL,
  request_id CHAR(36) NOT NULL,
  response_id CHAR(36) NOT NULL,
  responder_party_id CHAR(36) NULL,
  partner_id CHAR(36) NULL,
  status ENUM('DRAFT','SUBMITTED','SHORTLISTED','NEGOTIATING','ACCEPTED','REJECTED','WITHDRAWN','EXPIRED','SUPERSEDED') NOT NULL DEFAULT 'DRAFT',
  title VARCHAR(190) NOT NULL,
  current_version INT NOT NULL DEFAULT 1,
  selected_at DATETIME(0) NULL,
  accepted_at DATETIME(0) NULL,
  rejected_at DATETIME(0) NULL,
  withdrawn_at DATETIME(0) NULL,
  created_by CHAR(36) NULL,
  created_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_professional_proposal_response (response_id),
  KEY idx_professional_proposal_request_status (workspace_id,request_id,status),
  KEY idx_professional_proposal_workspace_status (workspace_id,status,created_at),
  KEY idx_professional_proposal_party_status (responder_party_id,status),
  KEY idx_professional_proposal_partner_status (partner_id,status),
  CONSTRAINT fk_professional_proposal_workspace FOREIGN KEY (workspace_id) REFERENCES workspaces(id) ON DELETE RESTRICT,
  CONSTRAINT fk_professional_proposal_request FOREIGN KEY (request_id) REFERENCES commercial_requests(id) ON DELETE CASCADE,
  CONSTRAINT fk_professional_proposal_response FOREIGN KEY (response_id) REFERENCES commercial_request_responses(id) ON DELETE CASCADE,
  CONSTRAINT fk_professional_proposal_party FOREIGN KEY (responder_party_id) REFERENCES commercial_parties(id) ON DELETE SET NULL,
  CONSTRAINT fk_professional_proposal_partner FOREIGN KEY (partner_id) REFERENCES partners(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE professional_proposal_versions (
  id CHAR(36) NOT NULL,
  proposal_id CHAR(36) NOT NULL,
  version_number INT NOT NULL,
  scope TEXT NULL,
  methodology TEXT NULL,
  deliverables JSON NULL,
  timeline TEXT NULL,
  assumptions TEXT NULL,
  exclusions TEXT NULL,
  amount DECIMAL(15,2) NULL,
  currency VARCHAR(10) NOT NULL DEFAULT 'ETB',
  taxes_and_fees TEXT NULL,
  validity_until DATETIME(0) NULL,
  team JSON NULL,
  qualifications JSON NULL,
  attachments JSON NULL,
  terms TEXT NULL,
  snapshot JSON NULL,
  superseded_at DATETIME(0) NULL,
  created_by CHAR(36) NULL,
  created_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_professional_proposal_version (proposal_id,version_number),
  KEY idx_professional_proposal_version_created (proposal_id,created_at),
  KEY idx_professional_proposal_version_validity (validity_until),
  CONSTRAINT fk_professional_proposal_version_proposal FOREIGN KEY (proposal_id) REFERENCES professional_proposals(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;