-- CE-11: External payment evidence
CREATE TABLE `external_payment_evidence` (
  `workspace_id` CHAR(36) NOT NULL,
  `id` CHAR(36) NOT NULL,
  `evidence_number` VARCHAR(80) NOT NULL,
  `status` ENUM('DRAFT','SUBMITTED','UNDER_REVIEW','VERIFIED','REJECTED','VOIDED') NOT NULL DEFAULT 'DRAFT',
  `source` ENUM('SELLER_REPORTED','CUSTOMER_REPORTED','PARTNER_REPORTED','OPERATOR_RECORDED','EXTERNAL_GATEWAY','INSTITUTIONAL_PROCUREMENT') NOT NULL,
  `payment_method` ENUM('BANK_TRANSFER','CASH','EXTERNAL_GATEWAY','INSTITUTIONAL_PROCUREMENT','CHEQUE','OTHER') NOT NULL,
  `order_id` CHAR(36) NULL,
  `payment_id` CHAR(36) NULL,
  `revenue_id` CHAR(36) NULL,
  `commercial_agreement_id` CHAR(36) NULL,
  `deal_registration_id` CHAR(36) NULL,
  `amount` DECIMAL(15,2) NOT NULL,
  `currency` VARCHAR(10) NOT NULL DEFAULT 'ETB',
  `payment_date` DATETIME(0) NOT NULL,
  `payer_name` VARCHAR(190) NULL,
  `payer_reference` VARCHAR(190) NULL,
  `payee_name` VARCHAR(190) NULL,
  `payee_reference` VARCHAR(190) NULL,
  `external_reference` VARCHAR(190) NULL,
  `evidence_attachments` JSON NULL,
  `notes` TEXT NULL,
  `recorded_by` CHAR(36) NULL,
  `verified_by` CHAR(36) NULL,
  `verified_at` DATETIME(0) NULL,
  `rejected_at` DATETIME(0) NULL,
  `rejection_reason` TEXT NULL,
  `voided_at` DATETIME(0) NULL,
  `created_at` DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_external_payment_evidence_number` (`evidence_number`),
  UNIQUE KEY `uq_external_payment_evidence_payment` (`payment_id`),
  UNIQUE KEY `uq_external_payment_evidence_revenue` (`revenue_id`),
  KEY `idx_external_payment_evidence_workspace_status` (`workspace_id`,`status`,`created_at`),
  KEY `idx_external_payment_evidence_order` (`workspace_id`,`order_id`,`created_at`),
  KEY `idx_external_payment_evidence_external_ref` (`external_reference`),
  KEY `idx_external_payment_evidence_payment_date` (`payment_date`,`status`),
  KEY `idx_external_payment_evidence_deal` (`deal_registration_id`),
  CONSTRAINT `fk_external_payment_evidence_workspace` FOREIGN KEY (`workspace_id`) REFERENCES `workspaces` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk_external_payment_evidence_order` FOREIGN KEY (`order_id`) REFERENCES `orders` (`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `fk_external_payment_evidence_payment` FOREIGN KEY (`payment_id`) REFERENCES `payments` (`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `fk_external_payment_evidence_revenue` FOREIGN KEY (`revenue_id`) REFERENCES `revenues` (`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `fk_external_payment_evidence_agreement` FOREIGN KEY (`commercial_agreement_id`) REFERENCES `commercial_agreements` (`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `fk_external_payment_evidence_deal` FOREIGN KEY (`deal_registration_id`) REFERENCES `commercial_deal_registrations` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;