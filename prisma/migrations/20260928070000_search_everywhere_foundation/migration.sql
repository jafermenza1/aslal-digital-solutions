CREATE TABLE search_profiles (
  id CHAR(36) NOT NULL,
  workspace_id CHAR(36) NOT NULL,
  target_type VARCHAR(20) NOT NULL,
  target_id VARCHAR(36) NOT NULL,
  locale VARCHAR(12) NOT NULL DEFAULT 'en',
  seo_title VARCHAR(180) NULL,
  meta_description VARCHAR(320) NULL,
  keywords TEXT NULL,
  canonical_url VARCHAR(1000) NULL,
  noindex TINYINT(1) NOT NULL DEFAULT 0,
  schema_type VARCHAR(50) NULL,
  entity_name VARCHAR(250) NULL,
  entity_description TEXT NULL,
  category VARCHAR(190) NULL,
  audience TEXT NULL,
  service_area TEXT NULL,
  local_context TEXT NULL,
  problem_statement TEXT NULL,
  direct_answer TEXT NULL,
  key_facts TEXT NULL,
  faq_json LONGTEXT NULL,
  same_as_json LONGTEXT NULL,
  citations_json LONGTEXT NULL,
  last_reviewed_at DATETIME NULL,
  updated_by VARCHAR(190) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_search_profile_target_locale (workspace_id,target_type,target_id,locale),
  KEY idx_search_profile_workspace_type (workspace_id,target_type),
  CONSTRAINT fk_search_profile_workspace FOREIGN KEY (workspace_id) REFERENCES workspaces(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;