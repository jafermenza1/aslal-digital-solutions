CREATE TABLE `commercial_listings` (
  `id` CHAR(36) NOT NULL,
  `workspace_id` CHAR(36) NOT NULL,
  `product_id` CHAR(36) NULL,
  `title` VARCHAR(190) NOT NULL,
  `slug` VARCHAR(160) NOT NULL,
  `listing_type` ENUM('PRODUCT','SERVICE','ASSET','PROPERTY') NOT NULL,
  `status` ENUM('DRAFT','PENDING_REVIEW','APPROVED','PUBLISHED','PAUSED','SOLD_OUT','EXPIRED','ARCHIVED','REJECTED') NOT NULL DEFAULT 'DRAFT',
  `description` TEXT NULL,
  `category` VARCHAR(100) NOT NULL DEFAULT 'General',
  `condition` VARCHAR(60) NULL,
  `location` VARCHAR(190) NULL,
  `asking_price` DECIMAL(15,2) NULL,
  `currency` VARCHAR(10) NOT NULL DEFAULT 'ETB',
  `price_label` VARCHAR(100) NULL,
  `inspection_required` BOOLEAN NOT NULL DEFAULT false,
  `request_quote` BOOLEAN NOT NULL DEFAULT true,
  `public_visible` BOOLEAN NOT NULL DEFAULT false,
  `featured` BOOLEAN NOT NULL DEFAULT false,
  `metadata` JSON NULL,
  `published_at` DATETIME(0) NULL,
  `expires_at` DATETIME(0) NULL,
  `created_by` CHAR(36) NULL,
  `created_at` DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_commercial_listing_workspace_slug` (`workspace_id`,`slug`),
  KEY `idx_commercial_listing_workspace_status_public` (`workspace_id`,`status`,`public_visible`),
  KEY `idx_commercial_listing_product` (`product_id`),
  KEY `idx_commercial_listing_type_category_status` (`listing_type`,`category`,`status`),
  CONSTRAINT `fk_commercial_listing_workspace` FOREIGN KEY (`workspace_id`) REFERENCES `workspaces` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_commercial_listing_product` FOREIGN KEY (`product_id`) REFERENCES `products` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
