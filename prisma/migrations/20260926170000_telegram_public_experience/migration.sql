CREATE TABLE telegram_public_sessions (
  id CHAR(36) NOT NULL,
  workspace_id CHAR(36) NOT NULL,
  telegram_user_id VARCHAR(80) NOT NULL,
  chat_id VARCHAR(80) NOT NULL,
  username VARCHAR(190) NULL,
  first_name VARCHAR(160) NULL,
  last_name VARCHAR(160) NULL,
  state VARCHAR(50) NOT NULL DEFAULT 'WELCOME',
  state_data JSON NULL,
  lead_id CHAR(36) NULL,
  person_id CHAR(36) NULL,
  support_requested_at DATETIME(0) NULL,
  last_inbound_at DATETIME(0) NULL,
  last_outbound_at DATETIME(0) NULL,
  created_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_tg_public_session_workspace_user (workspace_id, telegram_user_id),
  KEY idx_tg_public_session_state (workspace_id, state, updated_at),
  KEY idx_tg_public_session_chat (chat_id),
  CONSTRAINT fk_tg_public_session_workspace FOREIGN KEY (workspace_id) REFERENCES workspaces(id) ON DELETE CASCADE,
  CONSTRAINT fk_tg_public_session_lead FOREIGN KEY (lead_id) REFERENCES leads(id) ON DELETE SET NULL,
  CONSTRAINT fk_tg_public_session_person FOREIGN KEY (person_id) REFERENCES persons(id) ON DELETE SET NULL
);