CREATE TABLE `email_outbox` (
  `id` char(36) NOT NULL,
  `workspace_id` char(36) NOT NULL,
  `lead_id` char(36) NULL,
  `person_id` char(36) NULL,
  `customer_id` char(36) NULL,
  `opportunity_id` char(36) NULL,
  `message_id` char(36) NULL,
  `status` enum('DRAFT','QUEUED','SENDING','SENT','FAILED','DISCARDED') NOT NULL DEFAULT 'QUEUED',
  `message_type` enum('TRANSACTIONAL','MARKETING') NOT NULL DEFAULT 'TRANSACTIONAL',
  `template_key` varchar(120) NULL,
  `recipient_address` varchar(190) NOT NULL,
  `sender_address` varchar(190) NULL,
  `reply_to_address` varchar(190) NULL,
  `subject` varchar(250) NOT NULL,
  `html_body` text NOT NULL,
  `text_body` text NOT NULL,
  `original_subject` varchar(250) NOT NULL,
  `original_html_body` text NOT NULL,
  `original_text_body` text NOT NULL,
  `failure_reason` text NULL,
  `provider` varchar(60) NULL,
  `provider_message_id` varchar(255) NULL,
  `provider_response` json NULL,
  `attempt_count` int NOT NULL DEFAULT 0,
  `max_attempts` int NOT NULL DEFAULT 3,
  `next_attempt_at` datetime(0) NULL,
  `last_attempt_at` datetime(0) NULL,
  `sent_at` datetime(0) NULL,
  `discarded_at` datetime(0) NULL,
  `created_by` varchar(190) NULL,
  `created_at` datetime(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime(0) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_email_outbox_workspace_status_next` (`workspace_id`,`status`,`next_attempt_at`),
  KEY `idx_email_outbox_workspace_created` (`workspace_id`,`created_at`),
  KEY `idx_email_outbox_recipient_status` (`recipient_address`,`status`),
  KEY `idx_email_outbox_lead_created` (`lead_id`,`created_at`),
  KEY `idx_email_outbox_template_status` (`template_key`,`status`),
  CONSTRAINT `fk_email_outbox_workspace` FOREIGN KEY (`workspace_id`) REFERENCES `workspaces` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `email_delivery_attempts` (
  `id` char(36) NOT NULL,
  `outbox_id` char(36) NOT NULL,
  `attempt_number` int NOT NULL,
  `status` enum('SENT','FAILED') NOT NULL,
  `provider` varchar(60) NULL,
  `provider_message_id` varchar(255) NULL,
  `error` text NULL,
  `response` json NULL,
  `attempted_at` datetime(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_email_attempt_outbox_number` (`outbox_id`,`attempt_number`),
  KEY `idx_email_attempt_outbox_attempted` (`outbox_id`,`attempted_at`),
  CONSTRAINT `fk_email_attempt_outbox` FOREIGN KEY (`outbox_id`) REFERENCES `email_outbox` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `email_events` (
  `id` char(36) NOT NULL,
  `outbox_id` char(36) NOT NULL,
  `event_type` enum('SENT','DELIVERED','BOUNCED','FAILED','OPENED','CLICKED','REPLIED','UNSUBSCRIBED') NOT NULL,
  `provider_event_id` varchar(255) NULL,
  `metadata` json NULL,
  `occurred_at` datetime(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_email_event_outbox_occurred` (`outbox_id`,`occurred_at`),
  KEY `idx_email_event_type_occurred` (`event_type`,`occurred_at`),
  KEY `idx_email_event_provider` (`provider_event_id`),
  CONSTRAINT `fk_email_event_outbox` FOREIGN KEY (`outbox_id`) REFERENCES `email_outbox` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `email_automation_rules` (
  `id` char(36) NOT NULL,
  `workspace_id` char(36) NULL,
  `system_key` varchar(120) NOT NULL,
  `name` varchar(190) NOT NULL,
  `description` text NULL,
  `trigger_event` varchar(80) NOT NULL,
  `template_key` varchar(120) NOT NULL,
  `message_type` enum('TRANSACTIONAL','MARKETING') NOT NULL DEFAULT 'TRANSACTIONAL',
  `delay_minutes` int NOT NULL DEFAULT 0,
  `active` tinyint(1) NOT NULL DEFAULT 1,
  `conditions` json NULL,
  `stop_conditions` json NULL,
  `created_by` varchar(190) NULL,
  `created_at` datetime(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime(0) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `email_automation_rules_system_key_key` (`system_key`),
  KEY `idx_email_rule_workspace_trigger` (`workspace_id`,`trigger_event`,`active`),
  KEY `idx_email_rule_trigger_active` (`trigger_event`,`active`),
  CONSTRAINT `fk_email_rule_workspace` FOREIGN KEY (`workspace_id`) REFERENCES `workspaces` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
