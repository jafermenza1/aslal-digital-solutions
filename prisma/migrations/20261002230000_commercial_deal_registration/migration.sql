CREATE TABLE `commercial_deal_registrations` (
  `id` CHAR(36) NOT NULL,
  `workspace_id` CHAR(36) NOT NULL,
  `listing_id` CHAR(36) NOT NULL,
  `partner_id` CHAR(36) NOT NULL,
  `authorization_id` CHAR(36) NULL,
  `lead_id` CHAR(36) NOT NULL,
  `opportunity_id` CHAR(36) NULL,
  `status` ENUM('REQUESTED','APPROVED','REJECTED','PROTECTED','EXPIRED','CONVERTED','DISPUTED') NOT NULL DEFAULT 'REQUESTED',
  `source` VARCHAR(100) NULL,
  `buyer_name` VARCHAR(190) NULL,
  `buyer_email` VARCHAR(190) NULL,
  `buyer_phone` VARCHAR(40) NULL,
  `estimated_value` DECIMAL(15,2) NULL,
  `currency` VARCHAR(10) NOT NULL DEFAULT 'ETB',
  `notes` TEXT NULL,
  `evidence` JSON NULL,
  `requested_at` DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP(0),
  `reviewed_at` DATETIME(0) NULL,
  `protected_from` DATETIME(0) NULL,
  `protected_until` DATETIME(0) NULL,
  `rejected_at` DATETIME(0) NULL,
  `rejection_reason` TEXT NULL,
  `converted_at` DATETIME(0) NULL,
  `disputed_at` DATETIME(0) NULL,
  `created_by` CHAR(36) NULL,
  `reviewed_by` CHAR(36) NULL,
  `created_at` DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP(0),
  `updated_at` DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP(0),
  PRIMARY KEY (`id`),
  INDEX `idx_commercial_deal_workspace_status` (`workspace_id`,`status`,`requested_at`),
  INDEX `idx_commercial_deal_listing_status` (`listing_id`,`status`,`protected_until`),
  INDEX `idx_commercial_deal_partner_status` (`partner_id`,`status`),
  INDEX `idx_commercial_deal_lead_status` (`lead_id`,`status`),
  INDEX `idx_commercial_deal_opportunity` (`opportunity_id`),
  CONSTRAINT `fk_commercial_deal_workspace` FOREIGN KEY (`workspace_id`) REFERENCES `workspaces` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk_commercial_deal_listing` FOREIGN KEY (`listing_id`) REFERENCES `commercial_listings` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk_commercial_deal_partner` FOREIGN KEY (`partner_id`) REFERENCES `partners` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk_commercial_deal_authorization` FOREIGN KEY (`authorization_id`) REFERENCES `commercial_listing_authorizations` (`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `fk_commercial_deal_lead` FOREIGN KEY (`lead_id`) REFERENCES `leads` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk_commercial_deal_opportunity` FOREIGN KEY (`opportunity_id`) REFERENCES `opportunities` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci ENGINE=InnoDB;
