-- CE-6 complete demand-side commercial workflow
CREATE TABLE `commercial_requests` (
  `id` CHAR(36) NOT NULL,
  `workspace_id` CHAR(36) NOT NULL,
  `request_type` ENUM('BUY_REQUEST','ASSET_REQUEST','SERVICE_REQUEST','RFP') NOT NULL,
  `status` ENUM('DRAFT','SUBMITTED','QUALIFYING','PUBLISHED','MATCHING','RESPONSES_OPEN','NEGOTIATING','FULFILLED','CANCELLED','EXPIRED','CLOSED') NOT NULL DEFAULT 'SUBMITTED',
  `title` VARCHAR(190) NOT NULL,
  `category` VARCHAR(100) NULL,
  `requested_item` VARCHAR(250) NULL,
  `description` TEXT NULL,
  `quantity` DECIMAL(15,3) NULL,
  `condition_preference` VARCHAR(60) NULL,
  `budget_min` DECIMAL(15,2) NULL,
  `budget_max` DECIMAL(15,2) NULL,
  `currency` VARCHAR(10) NOT NULL DEFAULT 'ETB',
  `location` VARCHAR(190) NULL,
  `service_area` VARCHAR(190) NULL,
  `deadline` DATETIME(0) NULL,
  `organization_name` VARCHAR(190) NULL,
  `contact_name` VARCHAR(160) NOT NULL,
  `contact_email` VARCHAR(190) NULL,
  `contact_phone` VARCHAR(40) NULL,
  `contact_preference` VARCHAR(40) NULL,
  `privacy_visibility` VARCHAR(30) NOT NULL DEFAULT 'CONTROLLED',
  `source` VARCHAR(100) NULL,
  `campaign` VARCHAR(150) NULL,
  `partner_id` CHAR(36) NULL,
  `lead_id` CHAR(36) NULL,
  `opportunity_id` CHAR(36) NULL,
  `specifications` JSON NULL,
  `attachments` JSON NULL,
  `qualification_notes` TEXT NULL,
  `published_at` DATETIME(0) NULL,
  `qualified_at` DATETIME(0) NULL,
  `closed_at` DATETIME(0) NULL,
  `created_by` CHAR(36) NULL,
  `created_at` DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  INDEX `idx_commercial_request_workspace_status` (`workspace_id`,`status`,`created_at`),
  INDEX `idx_commercial_request_type_status` (`workspace_id`,`request_type`,`status`),
  INDEX `idx_commercial_request_lead_status` (`lead_id`,`status`),
  INDEX `idx_commercial_request_opportunity` (`opportunity_id`),
  INDEX `idx_commercial_request_partner_status` (`partner_id`,`status`),
  INDEX `idx_commercial_request_deadline_status` (`deadline`,`status`),
  CONSTRAINT `fk_commercial_request_workspace` FOREIGN KEY (`workspace_id`) REFERENCES `workspaces`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk_commercial_request_partner` FOREIGN KEY (`partner_id`) REFERENCES `partners`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `fk_commercial_request_lead` FOREIGN KEY (`lead_id`) REFERENCES `leads`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `fk_commercial_request_opportunity` FOREIGN KEY (`opportunity_id`) REFERENCES `opportunities`(`id`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `commercial_request_responses` (
  `id` CHAR(36) NOT NULL,
  `workspace_id` CHAR(36) NOT NULL,
  `request_id` CHAR(36) NOT NULL,
  `responder_party_id` CHAR(36) NULL,
  `partner_id` CHAR(36) NULL,
  `listing_id` CHAR(36) NULL,
  `status` ENUM('INVITED','RESPONDED','SHORTLISTED','REJECTED','WITHDRAWN','ACCEPTED') NOT NULL DEFAULT 'RESPONDED',
  `responder_name` VARCHAR(190) NOT NULL,
  `message` TEXT NULL,
  `quoted_amount` DECIMAL(15,2) NULL,
  `currency` VARCHAR(10) NOT NULL DEFAULT 'ETB',
  `availability` VARCHAR(190) NULL,
  `estimated_delivery` VARCHAR(190) NULL,
  `terms` TEXT NULL,
  `evidence` JSON NULL,
  `opportunity_id` CHAR(36) NULL,
  `quote_id` CHAR(36) NULL,
  `order_id` CHAR(36) NULL,
  `accepted_at` DATETIME(0) NULL,
  `rejected_at` DATETIME(0) NULL,
  `created_by` CHAR(36) NULL,
  `created_at` DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  INDEX `idx_commercial_response_request_status` (`workspace_id`,`request_id`,`status`),
  INDEX `idx_commercial_response_workspace_status` (`workspace_id`,`status`,`created_at`),
  INDEX `idx_commercial_response_party_status` (`responder_party_id`,`status`),
  INDEX `idx_commercial_response_partner_status` (`partner_id`,`status`),
  INDEX `idx_commercial_response_listing_status` (`listing_id`,`status`),
  CONSTRAINT `fk_commercial_response_workspace` FOREIGN KEY (`workspace_id`) REFERENCES `workspaces`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk_commercial_response_request` FOREIGN KEY (`request_id`) REFERENCES `commercial_requests`(`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `fk_commercial_response_party` FOREIGN KEY (`responder_party_id`) REFERENCES `commercial_parties`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `fk_commercial_response_partner` FOREIGN KEY (`partner_id`) REFERENCES `partners`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `fk_commercial_response_listing` FOREIGN KEY (`listing_id`) REFERENCES `commercial_listings`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `fk_commercial_response_opportunity` FOREIGN KEY (`opportunity_id`) REFERENCES `opportunities`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `fk_commercial_response_quote` FOREIGN KEY (`quote_id`) REFERENCES `quotes`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `fk_commercial_response_order` FOREIGN KEY (`order_id`) REFERENCES `orders`(`id`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
