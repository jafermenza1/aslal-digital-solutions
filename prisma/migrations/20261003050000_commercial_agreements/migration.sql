-- CE-10 Commercial Agreements
CREATE TABLE commercial_agreements (
  id CHAR(36) NOT NULL,
  workspace_id CHAR(36) NOT NULL,
  agreement_type ENUM('PARTNER_COMMERCIAL','SUPPLIER','RESELLER','SERVICE_PROVIDER','DEAL_PROTECTION','CUSTOMER_COMMERCIAL','CUSTOM') NOT NULL,
  status ENUM('DRAFT','PENDING_ACCEPTANCE','ACTIVE','SUSPENDED','EXPIRED','TERMINATED','DECLINED') NOT NULL DEFAULT 'DRAFT',
  title VARCHAR(190) NOT NULL,
  reference_number VARCHAR(80) NOT NULL,
  listing_id CHAR(36) NULL,
  program_id CHAR(36) NULL,
  commission_contract_id CHAR(36) NULL,
  deal_registration_id CHAR(36) NULL,
  proposal_id CHAR(36) NULL,
  protection_days INT NULL,
  attribution_policy ENUM('LAST_CLICK','FIRST_CLICK','LEAD_REGISTRATION','DEAL_REGISTRATION','PROMO_CODE','MANUAL_APPROVAL') NULL,
  attribution_window_days INT NULL,
  commission_model VARCHAR(80) NULL,
  commission_rate DECIMAL(15,4) NULL,
  commission_amount DECIMAL(15,2) NULL,
  commission_currency VARCHAR(10) NOT NULL DEFAULT 'ETB',
  payment_basis VARCHAR(190) NULL,
  territory VARCHAR(190) NULL,
  channel VARCHAR(100) NULL,
  exclusions TEXT NULL,
  anti_circumvention TEXT NULL,
  terms_text TEXT NULL,
  effective_at DATETIME(0) NULL,
  expires_at DATETIME(0) NULL,
  accepted_at DATETIME(0) NULL,
  accepted_by CHAR(36) NULL,
  created_by CHAR(36) NULL,
  created_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_commercial_agreement_reference (reference_number),
  KEY idx_commercial_agreement_workspace_status (workspace_id,status,effective_at),
  KEY idx_commercial_agreement_type_status (workspace_id,agreement_type,status),
  KEY idx_commercial_agreement_listing_status (listing_id,status),
  KEY idx_commercial_agreement_program_status (program_id,status),
  KEY idx_commercial_agreement_deal (deal_registration_id),
  KEY idx_commercial_agreement_proposal (proposal_id),
  CONSTRAINT fk_commercial_agreement_workspace FOREIGN KEY (workspace_id) REFERENCES workspaces(id) ON DELETE RESTRICT,
  CONSTRAINT fk_commercial_agreement_listing FOREIGN KEY (listing_id) REFERENCES commercial_listings(id) ON DELETE SET NULL,
  CONSTRAINT fk_commercial_agreement_program FOREIGN KEY (program_id) REFERENCES partner_programs(id) ON DELETE SET NULL,
  CONSTRAINT fk_commercial_agreement_commission_contract FOREIGN KEY (commission_contract_id) REFERENCES commission_contracts(id) ON DELETE SET NULL,
  CONSTRAINT fk_commercial_agreement_deal FOREIGN KEY (deal_registration_id) REFERENCES commercial_deal_registrations(id) ON DELETE SET NULL,
  CONSTRAINT fk_commercial_agreement_proposal FOREIGN KEY (proposal_id) REFERENCES professional_proposals(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE commercial_agreement_participants (
  id CHAR(36) NOT NULL,
  agreement_id CHAR(36) NOT NULL,
  role ENUM('BUSINESS','SUPPLIER','PROVIDER','PARTNER','CUSTOMER','OWNER') NOT NULL,
  party_id CHAR(36) NULL,
  partner_id CHAR(36) NULL,
  display_name VARCHAR(190) NOT NULL,
  contact_snapshot JSON NULL,
  accepted_at DATETIME(0) NULL,
  accepted_by CHAR(36) NULL,
  created_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_agreement_participant_role (agreement_id,role),
  KEY idx_agreement_participant_party (party_id),
  KEY idx_agreement_participant_partner (partner_id),
  CONSTRAINT fk_agreement_participant_agreement FOREIGN KEY (agreement_id) REFERENCES commercial_agreements(id) ON DELETE CASCADE,
  CONSTRAINT fk_agreement_participant_party FOREIGN KEY (party_id) REFERENCES commercial_parties(id) ON DELETE SET NULL,
  CONSTRAINT fk_agreement_participant_partner FOREIGN KEY (partner_id) REFERENCES partners(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE commercial_agreement_versions (
  id CHAR(36) NOT NULL,
  agreement_id CHAR(36) NOT NULL,
  version_number INT NOT NULL,
  terms_snapshot JSON NOT NULL,
  created_by CHAR(36) NULL,
  created_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  superseded_at DATETIME(0) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_commercial_agreement_version (agreement_id,version_number),
  KEY idx_commercial_agreement_version_created (agreement_id,created_at),
  CONSTRAINT fk_commercial_agreement_version_agreement FOREIGN KEY (agreement_id) REFERENCES commercial_agreements(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE commercial_agreement_acceptances (
  id CHAR(36) NOT NULL,
  agreement_id CHAR(36) NOT NULL,
  participant_id CHAR(36) NOT NULL,
  version_number INT NOT NULL,
  accepted_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  accepted_by CHAR(36) NULL,
  acceptance_text TEXT NULL,
  evidence JSON NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_commercial_agreement_acceptance (agreement_id,participant_id,version_number),
  KEY idx_commercial_agreement_acceptance_participant (participant_id,accepted_at),
  CONSTRAINT fk_commercial_agreement_acceptance_agreement FOREIGN KEY (agreement_id) REFERENCES commercial_agreements(id) ON DELETE CASCADE,
  CONSTRAINT fk_commercial_agreement_acceptance_participant FOREIGN KEY (participant_id) REFERENCES commercial_agreement_participants(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE commercial_agreement_events (
  id CHAR(36) NOT NULL,
  agreement_id CHAR(36) NOT NULL,
  event_type VARCHAR(60) NOT NULL,
  actor_id CHAR(36) NULL,
  note TEXT NULL,
  snapshot JSON NULL,
  created_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_commercial_agreement_event_created (agreement_id,created_at),
  CONSTRAINT fk_commercial_agreement_event_agreement FOREIGN KEY (agreement_id) REFERENCES commercial_agreements(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;