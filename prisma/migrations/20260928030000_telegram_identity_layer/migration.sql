CREATE TABLE `telegram_identities` (
  `id` char(36) NOT NULL,
  `workspace_id` char(36) NOT NULL,
  `telegram_user_id` varchar(80) NOT NULL,
  `telegram_chat_id` varchar(80) DEFAULT NULL,
  `telegram_username` varchar(190) DEFAULT NULL,
  `first_name` varchar(160) DEFAULT NULL,
  `last_name` varchar(160) DEFAULT NULL,
  `language_code` varchar(20) DEFAULT NULL,
  `photo_url` varchar(1000) DEFAULT NULL,
  `visitor_id` char(36) DEFAULT NULL,
  `person_id` char(36) DEFAULT NULL,
  `lead_id` char(36) DEFAULT NULL,
  `customer_id` char(36) DEFAULT NULL,
  `user_id` char(36) DEFAULT NULL,
  `partner_id` char(36) DEFAULT NULL,
  `last_start_param` varchar(255) DEFAULT NULL,
  `last_event` varchar(80) DEFAULT NULL,
  `first_seen_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `last_seen_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `last_auth_at` datetime DEFAULT NULL,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_telegram_identity_workspace_user` (`workspace_id`,`telegram_user_id`),
  KEY `idx_telegram_identity_workspace_chat` (`workspace_id`,`telegram_chat_id`),
  KEY `idx_telegram_identity_workspace_lead` (`workspace_id`,`lead_id`),
  KEY `idx_telegram_identity_workspace_customer` (`workspace_id`,`customer_id`),
  KEY `idx_telegram_identity_username` (`telegram_username`),
  CONSTRAINT `fk_telegram_identity_workspace` FOREIGN KEY (`workspace_id`) REFERENCES `workspaces` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;