CREATE TABLE catalog_offers (
  id CHAR(36) NOT NULL,
  workspace_id CHAR(36) NOT NULL,
  product_id CHAR(36) NULL,
  resource_id CHAR(36) NULL,
  slug VARCHAR(180) NOT NULL,
  title VARCHAR(250) NOT NULL,
  short_description VARCHAR(500) NULL,
  description TEXT NULL,
  status ENUM('DRAFT','PUBLISHED','PAUSED','ARCHIVED') NOT NULL DEFAULT 'DRAFT',
  price_type ENUM('FIXED','STARTING_FROM','QUOTE','CONTACT') NOT NULL DEFAULT 'QUOTE',
  price DECIMAL(15,2) NULL,
  currency VARCHAR(10) NOT NULL DEFAULT 'ETB',
  cta_label VARCHAR(80) NOT NULL,
  cta_mode VARCHAR(40) NOT NULL DEFAULT 'REQUEST',
  terms TEXT NULL,
  eligibility TEXT NULL,
  display_order INT NOT NULL DEFAULT 0,
  featured TINYINT(1) NOT NULL DEFAULT 0,
  published_at DATETIME(0) NULL,
  created_by VARCHAR(190) NULL,
  created_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY(id),
  UNIQUE KEY uq_catalog_offer_workspace_slug(workspace_id,slug),
  KEY idx_catalog_offer_workspace_status_order(workspace_id,status,display_order),
  KEY idx_catalog_offer_product(product_id),
  KEY idx_catalog_offer_resource(resource_id),
  CONSTRAINT fk_catalog_offer_workspace FOREIGN KEY(workspace_id) REFERENCES workspaces(id) ON DELETE RESTRICT,
  CONSTRAINT fk_catalog_offer_product FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE RESTRICT,
  CONSTRAINT fk_catalog_offer_resource FOREIGN KEY(resource_id) REFERENCES resources(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE catalog_offer_channels (
  id CHAR(36) NOT NULL,
  offer_id CHAR(36) NOT NULL,
  channel ENUM('WEBSITE','PARTNER_MARKETPLACE','TELEGRAM') NOT NULL,
  enabled TINYINT(1) NOT NULL DEFAULT 1,
  headline VARCHAR(250) NULL,
  description TEXT NULL,
  cta_label VARCHAR(80) NULL,
  destination VARCHAR(1000) NULL,
  sort_order INT NOT NULL DEFAULT 0,
  created_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY(id),
  UNIQUE KEY uq_catalog_offer_channel(offer_id,channel),
  KEY idx_catalog_offer_channel_enabled(channel,enabled,sort_order),
  CONSTRAINT fk_catalog_offer_channel_offer FOREIGN KEY(offer_id) REFERENCES catalog_offers(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
