CREATE TABLE `telegram_templates` (
  `id` char(36) NOT NULL,
  `workspace_id` char(36) NOT NULL,
  `template_key` varchar(120) NOT NULL,
  `name` varchar(190) NOT NULL,
  `message_type` enum('TRANSACTIONAL','MARKETING','SALES','PARTNER','SUPPORT','SYSTEM') NOT NULL DEFAULT 'TRANSACTIONAL',
  `content_template` text NOT NULL,
  `media_type` varchar(30) DEFAULT NULL,
  `media_url_template` varchar(1000) DEFAULT NULL,
  `reply_markup` json DEFAULT NULL,
  `active` tinyint(1) NOT NULL DEFAULT 1,
  `allow_business_mode` tinyint(1) NOT NULL DEFAULT 1,
  `updated_by` varchar(190) DEFAULT NULL,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_telegram_template_workspace_key` (`workspace_id`,`template_key`),
  KEY `idx_telegram_template_workspace_active` (`workspace_id`,`active`,`message_type`),
  CONSTRAINT `fk_telegram_templates_workspace` FOREIGN KEY (`workspace_id`) REFERENCES `workspaces` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE `telegram_outbox` (
  `id` char(36) NOT NULL,
  `workspace_id` char(36) NOT NULL,
  `lead_id` char(36) DEFAULT NULL,
  `person_id` char(36) DEFAULT NULL,
  `customer_id` char(36) DEFAULT NULL,
  `opportunity_id` char(36) DEFAULT NULL,
  `conversation_id` char(36) DEFAULT NULL,
  `message_id` char(36) DEFAULT NULL,
  `template_key` varchar(120) DEFAULT NULL,
  `message_type` enum('TRANSACTIONAL','MARKETING','SALES','PARTNER','SUPPORT','SYSTEM') NOT NULL DEFAULT 'TRANSACTIONAL',
  `send_mode` enum('BOT','BUSINESS') NOT NULL DEFAULT 'BOT',
  `business_connection_id` varchar(190) DEFAULT NULL,
  `chat_id` varchar(80) NOT NULL,
  `message_thread_id` int DEFAULT NULL,
  `content` text NOT NULL,
  `media_type` varchar(30) DEFAULT NULL,
  `media_url` varchar(1000) DEFAULT NULL,
  `reply_markup` json DEFAULT NULL,
  `metadata` json DEFAULT NULL,
  `original_content` text NOT NULL,
  `original_reply_markup` json DEFAULT NULL,
  `status` enum('DRAFT','QUEUED','SENDING','SENT','FAILED','DISCARDED') NOT NULL DEFAULT 'QUEUED',
  `telegram_message_id` varchar(80) DEFAULT NULL,
  `telegram_response` json DEFAULT NULL,
  `failure_reason` text DEFAULT NULL,
  `attempt_count` int NOT NULL DEFAULT 0,
  `max_attempts` int NOT NULL DEFAULT 3,
  `next_attempt_at` datetime DEFAULT NULL,
  `last_attempt_at` datetime DEFAULT NULL,
  `sent_at` datetime DEFAULT NULL,
  `discarded_at` datetime DEFAULT NULL,
  `created_by` varchar(190) DEFAULT NULL,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_telegram_outbox_workspace_status_next` (`workspace_id`,`status`,`next_attempt_at`),
  KEY `idx_telegram_outbox_workspace_created` (`workspace_id`,`created_at`),
  KEY `idx_telegram_outbox_chat_status` (`chat_id`,`status`),
  KEY `idx_telegram_outbox_lead_created` (`lead_id`,`created_at`),
  CONSTRAINT `fk_telegram_outbox_workspace` FOREIGN KEY (`workspace_id`) REFERENCES `workspaces` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE `telegram_delivery_attempts` (
  `id` char(36) NOT NULL,
  `outbox_id` char(36) NOT NULL,
  `attempt_number` int NOT NULL,
  `status` enum('DRAFT','QUEUED','SENDING','SENT','FAILED','DISCARDED') NOT NULL,
  `response` json DEFAULT NULL,
  `error` text DEFAULT NULL,
  `attempted_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_telegram_attempt_outbox_number` (`outbox_id`,`attempt_number`),
  KEY `idx_telegram_attempt_outbox_attempted` (`outbox_id`,`attempted_at`),
  CONSTRAINT `fk_telegram_attempt_outbox` FOREIGN KEY (`outbox_id`) REFERENCES `telegram_outbox` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE `telegram_delivery_events` (
  `id` char(36) NOT NULL,
  `outbox_id` char(36) NOT NULL,
  `event_type` enum('SENT','FAILED','CALLBACK','REPLY','HANDOFF','EDITED','DELETED','BUTTON_CLICKED') NOT NULL,
  `metadata` json DEFAULT NULL,
  `occurred_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_telegram_event_outbox_occurred` (`outbox_id`,`occurred_at`),
  KEY `idx_telegram_event_type_occurred` (`event_type`,`occurred_at`),
  CONSTRAINT `fk_telegram_event_outbox` FOREIGN KEY (`outbox_id`) REFERENCES `telegram_outbox` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
