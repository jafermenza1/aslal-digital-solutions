  CONSTRAINT fk_reseller_territory_agreement FOREIGN KEY(agreement_id) REFERENCES reseller_agreements(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

