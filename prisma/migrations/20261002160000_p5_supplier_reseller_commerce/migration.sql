CREATE TABLE suppliers (
  id CHAR(36) NOT NULL,
  workspace_id CHAR(36) NOT NULL,
  supplier_number VARCHAR(40) NOT NULL,
  legal_name VARCHAR(190) NOT NULL,
  contact_name VARCHAR(160) NULL,
  email VARCHAR(190) NULL,
  phone VARCHAR(40) NULL,
  country VARCHAR(100) NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
  fulfillment_responsibility VARCHAR(30) NOT NULL DEFAULT 'SUPPLIER',
  return_responsibility VARCHAR(30) NOT NULL DEFAULT 'SUPPLIER',
  settlement_schedule VARCHAR(40) NOT NULL DEFAULT 'NET_30',
  settlement_currency VARCHAR(10) NOT NULL DEFAULT 'ETB',
  created_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY(id),
  UNIQUE KEY uq_supplier_number(supplier_number),
  KEY idx_suppliers_workspace_status(workspace_id,status),
  CONSTRAINT fk_suppliers_workspace FOREIGN KEY(workspace_id) REFERENCES workspaces(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE supplier_relationships (
  id CHAR(36) NOT NULL,
  workspace_id CHAR(36) NOT NULL,
  supplier_id CHAR(36) NOT NULL,
  product_id CHAR(36) NULL,
  resource_id CHAR(36) NULL,
  relationship_type VARCHAR(30) NOT NULL DEFAULT 'SUPPLY',
  status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
  territory_scope JSON NULL,
  fulfillment_terms JSON NULL,
  return_terms JSON NULL,
  settlement_terms JSON NULL,
  effective_from DATETIME(0) NULL,
  effective_until DATETIME(0) NULL,
  terms_snapshot JSON NULL,
  created_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY(id),
  KEY idx_supplier_rel_workspace_status(workspace_id,status),
  KEY idx_supplier_rel_supplier(supplier_id),
  KEY idx_supplier_rel_product(product_id),
  KEY idx_supplier_rel_resource(resource_id),
  CONSTRAINT fk_supplier_rel_workspace FOREIGN KEY(workspace_id) REFERENCES workspaces(id) ON DELETE RESTRICT,
  CONSTRAINT fk_supplier_rel_supplier FOREIGN KEY(supplier_id) REFERENCES suppliers(id) ON DELETE CASCADE,
  CONSTRAINT fk_supplier_rel_product FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE SET NULL,
  CONSTRAINT fk_supplier_rel_resource FOREIGN KEY(resource_id) REFERENCES resources(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE reseller_agreements (
  id CHAR(36) NOT NULL,
  workspace_id CHAR(36) NOT NULL,
  reseller_id CHAR(36) NOT NULL,
  supplier_relationship_id CHAR(36) NULL,
  agreement_number VARCHAR(50) NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
  currency VARCHAR(10) NOT NULL DEFAULT 'ETB',
  pricing_model VARCHAR(30) NOT NULL DEFAULT 'MARGIN',
  default_margin_percent DECIMAL(7,4) NOT NULL DEFAULT 0,
  permitted_discount_percent DECIMAL(7,4) NOT NULL DEFAULT 0,
  territory_scope JSON NULL,
  customer_ownership VARCHAR(30) NOT NULL DEFAULT 'BUSINESS',
  fulfillment_responsibility VARCHAR(30) NOT NULL DEFAULT 'BUSINESS',
  return_responsibility VARCHAR(30) NOT NULL DEFAULT 'BUSINESS',
  settlement_rule VARCHAR(40) NOT NULL DEFAULT 'ORDER_FULFILLED',
  settlement_schedule VARCHAR(40) NOT NULL DEFAULT 'NET_30',
  minimum_order_amount DECIMAL(15,2) NOT NULL DEFAULT 0,
  effective_from DATETIME(0) NULL,
  effective_until DATETIME(0) NULL,
  signed_at DATETIME(0) NULL,
  signed_by VARCHAR(190) NULL,
  terms_snapshot JSON NULL,
  created_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY(id),
  UNIQUE KEY uq_reseller_agreement_number(agreement_number),
  KEY idx_reseller_agreement_workspace_status(workspace_id,status),
  KEY idx_reseller_agreement_reseller_status(reseller_id,status),
  CONSTRAINT fk_reseller_agreement_workspace FOREIGN KEY(workspace_id) REFERENCES workspaces(id) ON DELETE RESTRICT,
  CONSTRAINT fk_reseller_agreement_reseller FOREIGN KEY(reseller_id) REFERENCES resellers(id) ON DELETE CASCADE,
  CONSTRAINT fk_reseller_agreement_supplier_rel FOREIGN KEY(supplier_relationship_id) REFERENCES supplier_relationships(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

