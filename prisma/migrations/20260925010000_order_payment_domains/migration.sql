CREATE TABLE `orders` (
  `id` CHAR(36) NOT NULL,
  `order_number` VARCHAR(60) NOT NULL,
  `quote_id` CHAR(36) NULL,
  `customer_id` CHAR(36) NULL,
  `opportunity_id` CHAR(36) NULL,
  `status` ENUM('DRAFT','CONFIRMED','FULFILLING','COMPLETED','CANCELLED') NOT NULL DEFAULT 'DRAFT',
  `currency` VARCHAR(10) NOT NULL DEFAULT 'ETB',
  `subtotal` DECIMAL(15,2) NOT NULL DEFAULT 0,
  `discount` DECIMAL(15,2) NOT NULL DEFAULT 0,
  `total` DECIMAL(15,2) NOT NULL DEFAULT 0,
  `payment_state` ENUM('INITIATED','PENDING','CONFIRMED','FAILED','REVERSED','REFUNDED') NOT NULL DEFAULT 'INITIATED',
  `fulfillment_state` VARCHAR(40) NOT NULL DEFAULT 'PENDING',
  `source` VARCHAR(100) NULL,
  `campaign` VARCHAR(150) NULL,
  `referral_code` VARCHAR(100) NULL,
  `partner_id` CHAR(36) NULL,
  `referral_link_id` CHAR(36) NULL,
  `sales_owner_email` VARCHAR(190) NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `confirmed_at` DATETIME NULL,
  `completed_at` DATETIME NULL,
  `cancelled_at` DATETIME NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `orders_order_number_key` (`order_number`),
  UNIQUE KEY `orders_quote_id_key` (`quote_id`),
  KEY `idx_orders_customer_created` (`customer_id`,`created_at`),
  KEY `idx_orders_opportunity_created` (`opportunity_id`,`created_at`),
  KEY `idx_orders_status_created` (`status`,`created_at`),
  KEY `idx_orders_partner_created` (`partner_id`,`created_at`),
  KEY `idx_orders_referral` (`referral_code`),
  CONSTRAINT `fk_orders_quote` FOREIGN KEY (`quote_id`) REFERENCES `quotes` (`id`) ON DELETE SET NULL,
  CONSTRAINT `fk_orders_customer` FOREIGN KEY (`customer_id`) REFERENCES `customers` (`id`) ON DELETE SET NULL,
  CONSTRAINT `fk_orders_opportunity` FOREIGN KEY (`opportunity_id`) REFERENCES `opportunities` (`id`) ON DELETE SET NULL,
  CONSTRAINT `fk_orders_partner` FOREIGN KEY (`partner_id`) REFERENCES `partners` (`id`) ON DELETE SET NULL,
  CONSTRAINT `fk_orders_referral` FOREIGN KEY (`referral_link_id`) REFERENCES `referral_links` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `order_items` (
  `id` CHAR(36) NOT NULL,
  `order_id` CHAR(36) NOT NULL,
  `description` VARCHAR(500) NOT NULL,
  `quantity` DECIMAL(15,3) NOT NULL DEFAULT 1,
  `unit_price` DECIMAL(15,2) NOT NULL,
  `discount` DECIMAL(15,2) NOT NULL DEFAULT 0,
  `line_total` DECIMAL(15,2) NOT NULL,
  `sort_order` INT NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  KEY `idx_order_items_order_sort` (`order_id`,`sort_order`),
  CONSTRAINT `fk_order_items_order` FOREIGN KEY (`order_id`) REFERENCES `orders` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `payments` (
  `id` CHAR(36) NOT NULL,
  `order_id` CHAR(36) NOT NULL,
  `customer_id` CHAR(36) NULL,
  `provider` VARCHAR(80) NOT NULL,
  `provider_transaction_ref` VARCHAR(190) NULL,
  `idempotency_key` VARCHAR(255) NOT NULL,
  `amount` DECIMAL(15,2) NOT NULL,
  `currency` VARCHAR(10) NOT NULL,
  `method` VARCHAR(50) NULL,
  `status` ENUM('INITIATED','PENDING','CONFIRMED','FAILED','REVERSED','REFUNDED') NOT NULL DEFAULT 'INITIATED',
  `reconciliation_status` ENUM('UNMATCHED','MATCHED','RECONCILED','EXCEPTION') NOT NULL DEFAULT 'UNMATCHED',
  `failure_reason` TEXT NULL,
  `reversal_reason` TEXT NULL,
  `refund_reason` TEXT NULL,
  `metadata` JSON NULL,
  `confirmed_at` DATETIME NULL,
  `reconciled_at` DATETIME NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `payments_idempotency_key_key` (`idempotency_key`),
  KEY `idx_payments_order_created` (`order_id`,`created_at`),
  KEY `idx_payments_status_created` (`status`,`created_at`),
  KEY `idx_payments_reconciliation_created` (`reconciliation_status`,`created_at`),
  KEY `idx_payments_provider_ref` (`provider`,`provider_transaction_ref`),
  CONSTRAINT `fk_payments_order` FOREIGN KEY (`order_id`) REFERENCES `orders` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_payments_customer` FOREIGN KEY (`customer_id`) REFERENCES `customers` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;