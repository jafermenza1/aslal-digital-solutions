CREATE TABLE commercial_distribution_items (
  id CHAR(36) NOT NULL,
  workspace_id CHAR(36) NOT NULL,
  name VARCHAR(190) NOT NULL,
  asset_type ENUM('TICKET','COUPON','VOUCHER','PASS') NOT NULL,
  description TEXT NULL,
  product_id CHAR(36) NULL,
  campaign_id CHAR(36) NULL,
  price DECIMAL(15,2) NULL,
  value DECIMAL(15,2) NULL,
  currency VARCHAR(10) NOT NULL DEFAULT 'ETB',
  inventory_limit INT NULL,
  starts_at DATETIME NULL,
  ends_at DATETIME NULL,
  redemption_instructions TEXT NULL,
  status ENUM('DRAFT','ACTIVE','PAUSED','ARCHIVED') NOT NULL DEFAULT 'DRAFT',
  created_by VARCHAR(190) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_dist_item_workspace_status (workspace_id,status),
  KEY idx_dist_item_workspace_campaign (workspace_id,campaign_id),
  KEY idx_dist_item_workspace_product (workspace_id,product_id),
  CONSTRAINT fk_dist_item_workspace FOREIGN KEY (workspace_id) REFERENCES workspaces(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE partner_sales_asset_allocations (
  id CHAR(36) NOT NULL,
  workspace_id CHAR(36) NOT NULL,
  asset_id CHAR(36) NOT NULL,
  partner_id CHAR(36) NOT NULL,
  campaign_id CHAR(36) NULL,
  quantity_allocated INT NOT NULL,
  quantity_issued INT NOT NULL DEFAULT 0,
  status ENUM('ACTIVE','PAUSED','EXPIRED','CLOSED') NOT NULL DEFAULT 'ACTIVE',
  starts_at DATETIME NULL,
  ends_at DATETIME NULL,
  created_by VARCHAR(190) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_sales_asset_allocation_asset_partner (asset_id,partner_id),
  KEY idx_sales_asset_allocation_partner (workspace_id,partner_id,status),
  KEY idx_sales_asset_allocation_asset (workspace_id,asset_id,status),
  CONSTRAINT fk_sales_asset_alloc_workspace FOREIGN KEY (workspace_id) REFERENCES workspaces(id) ON DELETE RESTRICT,
  CONSTRAINT fk_sales_asset_alloc_asset FOREIGN KEY (asset_id) REFERENCES commercial_distribution_items(id) ON DELETE CASCADE,
  CONSTRAINT fk_sales_asset_alloc_partner FOREIGN KEY (partner_id) REFERENCES partners(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE issued_sales_assets (
  id CHAR(36) NOT NULL,
  workspace_id CHAR(36) NOT NULL,
  asset_id CHAR(36) NOT NULL,
  allocation_id CHAR(36) NOT NULL,
  partner_id CHAR(36) NOT NULL,
  serial_number VARCHAR(50) NOT NULL,
  qr_payload VARCHAR(500) NOT NULL,
  holder_name VARCHAR(190) NULL,
  holder_phone VARCHAR(40) NULL,
  issued_price DECIMAL(15,2) NULL,
  issued_value DECIMAL(15,2) NULL,
  status ENUM('ISSUED','VALID','REDEEMED','EXPIRED','VOID') NOT NULL DEFAULT 'ISSUED',
  issued_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  valid_from DATETIME NULL,
  valid_until DATETIME NULL,
  issued_by VARCHAR(190) NULL,
  redeemed_at DATETIME NULL,
  redeemed_by VARCHAR(190) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_issued_sales_asset_workspace_serial (workspace_id,serial_number),
  KEY idx_issued_sales_asset_asset_status (workspace_id,asset_id,status),
  KEY idx_issued_sales_asset_partner_issued (workspace_id,partner_id,issued_at),
  KEY idx_issued_sales_asset_allocation_issued (allocation_id,issued_at),
  CONSTRAINT fk_issued_sales_asset_workspace FOREIGN KEY (workspace_id) REFERENCES workspaces(id) ON DELETE RESTRICT,
  CONSTRAINT fk_issued_sales_asset_asset FOREIGN KEY (asset_id) REFERENCES commercial_distribution_items(id) ON DELETE CASCADE,
  CONSTRAINT fk_issued_sales_asset_allocation FOREIGN KEY (allocation_id) REFERENCES partner_sales_asset_allocations(id) ON DELETE CASCADE,
  CONSTRAINT fk_issued_sales_asset_partner FOREIGN KEY (partner_id) REFERENCES partners(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
