CREATE TABLE `commercial_appointments` (
  `id` CHAR(36) NOT NULL,
  `workspace_id` CHAR(36) NOT NULL,
  `registration_id` CHAR(36) NOT NULL,
  `listing_id` CHAR(36) NOT NULL,
  `partner_id` CHAR(36) NOT NULL,
  `lead_id` CHAR(36) NOT NULL,
  `status` ENUM('REQUESTED','SCHEDULED','CONFIRMED','ATTENDED','COMPLETED','CANCELLED','NO_SHOW') NOT NULL DEFAULT 'REQUESTED',
  `outcome` ENUM('PENDING','INSPECTION_COMPLETED','INTERESTED','NEEDS_QUOTE','NEGOTIATING','NOT_INTERESTED','RESCHEDULE_REQUIRED','NOT_AS_DESCRIBED','NO_DECISION','OTHER') NOT NULL DEFAULT 'PENDING',
  `appointment_type` VARCHAR(60) NOT NULL DEFAULT 'INSPECTION',
  `scheduled_start` DATETIME(0) NULL,
  `scheduled_end` DATETIME(0) NULL,
  `location` VARCHAR(500) NULL,
  `meeting_notes` TEXT NULL,
  `customer_notes` TEXT NULL,
  `evidence` JSON NULL,
  `check_in_token_hash` VARCHAR(128) NULL,
  `check_in_at` DATETIME(0) NULL,
  `check_in_by` VARCHAR(190) NULL,
  `completed_at` DATETIME(0) NULL,
  `cancelled_at` DATETIME(0) NULL,
  `created_by` CHAR(36) NULL,
  `created_at` DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP(0),
  `updated_at` DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP(0),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_commercial_appt_checkin_token` (`check_in_token_hash`),
  INDEX `idx_commercial_appt_workspace_status` (`workspace_id`,`status`,`scheduled_start`),
  INDEX `idx_commercial_appt_registration_created` (`registration_id`,`created_at`),
  INDEX `idx_commercial_appt_listing_schedule` (`listing_id`,`scheduled_start`),
  INDEX `idx_commercial_appt_partner_status` (`partner_id`,`status`),
  INDEX `idx_commercial_appt_lead_schedule` (`lead_id`,`scheduled_start`),
  CONSTRAINT `fk_commercial_appt_workspace` FOREIGN KEY (`workspace_id`) REFERENCES `workspaces` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
