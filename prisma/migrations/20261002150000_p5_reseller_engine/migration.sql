CREATE TABLE resellers (
  id CHAR(36) NOT NULL,
  workspace_id CHAR(36) NOT NULL,
  partner_id CHAR(36) NOT NULL,
  reseller_number VARCHAR(40) NOT NULL,
  business_name VARCHAR(190) NULL,
  business_registration_number VARCHAR(100) NULL,
  tax_number VARCHAR(100) NULL,
  business_type VARCHAR(100) NULL,
  address VARCHAR(500) NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
  pricing_mode VARCHAR(30) NOT NULL DEFAULT 'MARGIN',
  default_currency VARCHAR(10) NOT NULL DEFAULT 'ETB',
  credit_limit DECIMAL(15,2) NOT NULL DEFAULT 0,
  approved_at DATETIME(0) NULL,
  approved_by VARCHAR(190) NULL,
  created_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_reseller_partner (partner_id),
  UNIQUE KEY uq_reseller_number (reseller_number),
  KEY idx_resellers_workspace_status (workspace_id,status),
  KEY idx_resellers_partner_status (partner_id,status),
  CONSTRAINT fk_resellers_workspace FOREIGN KEY (workspace_id) REFERENCES workspaces(id) ON DELETE RESTRICT,
  CONSTRAINT fk_resellers_partner FOREIGN KEY (partner_id) REFERENCES partners(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE reseller_offers (
  id CHAR(36) NOT NULL,
  workspace_id CHAR(36) NOT NULL,
  reseller_id CHAR(36) NOT NULL,
  product_id CHAR(36) NULL,
  campaign_id CHAR(36) NULL,
  name VARCHAR(190) NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
  currency VARCHAR(10) NOT NULL DEFAULT 'ETB',
  list_price DECIMAL(15,2) NOT NULL DEFAULT 0,
  reseller_price DECIMAL(15,2) NOT NULL DEFAULT 0,
  minimum_quantity DECIMAL(15,3) NOT NULL DEFAULT 1,
  maximum_quantity DECIMAL(15,3) NULL,
  valid_from DATETIME(0) NULL,
  valid_until DATETIME(0) NULL,
  terms_snapshot JSON NULL,
  created_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_reseller_offers_workspace_status (workspace_id,status),
  KEY idx_reseller_offers_reseller_status (reseller_id,status),
  KEY idx_reseller_offers_product (product_id),
  CONSTRAINT fk_reseller_offers_workspace FOREIGN KEY (workspace_id) REFERENCES workspaces(id) ON DELETE RESTRICT,
  CONSTRAINT fk_reseller_offers_reseller FOREIGN KEY (reseller_id) REFERENCES resellers(id) ON DELETE CASCADE,
  CONSTRAINT fk_reseller_offers_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE SET NULL,
  CONSTRAINT fk_reseller_offers_campaign FOREIGN KEY (campaign_id) REFERENCES partner_campaigns(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE reseller_orders (
  id CHAR(36) NOT NULL,
  workspace_id CHAR(36) NOT NULL,
  reseller_id CHAR(36) NOT NULL,
  order_id CHAR(36) NOT NULL,
  offer_id CHAR(36) NULL,
  reseller_order_number VARCHAR(60) NOT NULL,
  currency VARCHAR(10) NOT NULL DEFAULT 'ETB',
  quantity DECIMAL(15,3) NOT NULL DEFAULT 1,
  list_amount DECIMAL(15,2) NOT NULL DEFAULT 0,
  reseller_amount DECIMAL(15,2) NOT NULL DEFAULT 0,
  margin_amount DECIMAL(15,2) NOT NULL DEFAULT 0,
  status VARCHAR(30) NOT NULL DEFAULT 'REGISTERED',
  terms_snapshot JSON NULL,
  created_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_reseller_order_order (order_id),
  UNIQUE KEY uq_reseller_order_number (reseller_order_number),
  KEY idx_reseller_orders_reseller_status (reseller_id,status),
  KEY idx_reseller_orders_workspace_created (workspace_id,created_at),
  CONSTRAINT fk_reseller_orders_workspace FOREIGN KEY (workspace_id) REFERENCES workspaces(id) ON DELETE RESTRICT,
  CONSTRAINT fk_reseller_orders_reseller FOREIGN KEY (reseller_id) REFERENCES resellers(id) ON DELETE RESTRICT,
  CONSTRAINT fk_reseller_orders_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE RESTRICT,
  CONSTRAINT fk_reseller_orders_offer FOREIGN KEY (offer_id) REFERENCES reseller_offers(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
