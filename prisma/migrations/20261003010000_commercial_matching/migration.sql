CREATE TABLE `commercial_matches` (
  `id` CHAR(36) NOT NULL,
  `workspace_id` CHAR(36) NOT NULL,
  `request_id` CHAR(36) NOT NULL,
  `listing_id` CHAR(36) NOT NULL,
  `partner_id` CHAR(36) NULL,
  `supplier_party_id` CHAR(36) NULL,
  `status` ENUM('SUGGESTED','SHORTLISTED','CONTACTED','RESPONDED','REJECTED','EXPIRED','CONVERTED') NOT NULL DEFAULT 'SUGGESTED',
  `score` INT NOT NULL,
  `score_breakdown` JSON NOT NULL,
  `reasons` JSON NOT NULL,
  `eligibility` VARCHAR(40) NULL,
  `eligibility_reasons` JSON NULL,
  `evaluated_at` DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `expires_at` DATETIME(0) NULL,
  `reviewed_at` DATETIME(0) NULL,
  `reviewed_by` CHAR(36) NULL,
  `review_reason` TEXT NULL,
  `response_id` CHAR(36) NULL,
  `created_at` DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY `uq_commercial_match_request_listing` (`request_id`,`listing_id`),
  KEY `idx_commercial_match_workspace_status_score` (`workspace_id`,`status`,`score`),
  KEY `idx_commercial_match_request_status_score` (`request_id`,`status`,`score`),
  KEY `idx_commercial_match_listing_status` (`listing_id`,`status`),
  KEY `idx_commercial_match_partner_status` (`partner_id`,`status`),
  CONSTRAINT `fk_commercial_match_workspace` FOREIGN KEY (`workspace_id`) REFERENCES `workspaces` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_commercial_match_request` FOREIGN KEY (`request_id`) REFERENCES `commercial_requests` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_commercial_match_listing` FOREIGN KEY (`listing_id`) REFERENCES `commercial_listings` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_commercial_match_partner` FOREIGN KEY (`partner_id`) REFERENCES `partners` (`id`) ON DELETE SET NULL,
  CONSTRAINT `fk_commercial_match_supplier_party` FOREIGN KEY (`supplier_party_id`) REFERENCES `commercial_parties` (`id`) ON DELETE SET NULL,
  CONSTRAINT `fk_commercial_match_response` FOREIGN KEY (`response_id`) REFERENCES `commercial_request_responses` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;