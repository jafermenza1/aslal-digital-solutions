CREATE TABLE `agent_deal_registrations` (
  `id` CHAR(36) NOT NULL,
  `workspace_id` CHAR(36) NOT NULL,
  `partner_id` CHAR(36) NOT NULL,
  `lead_id` CHAR(36) NOT NULL,
  `opportunity_id` CHAR(36) NULL,
  `program_id` CHAR(36) NULL,
  `campaign_id` CHAR(36) NULL,
  `status` ENUM('SUBMITTED','UNDER_REVIEW','ACCEPTED','REJECTED','EXPIRED','COMPLETED') NOT NULL DEFAULT 'SUBMITTED',
  `claim_reason` TEXT NOT NULL,
  `customer_introduced_at` DATETIME NULL,
  `accepted_at` DATETIME NULL,
  `accepted_by` VARCHAR(190) NULL,
  `rejected_at` DATETIME NULL,
  `rejection_reason` TEXT NULL,
  `completed_at` DATETIME NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_agent_deal_partner_lead` (`workspace_id`,`partner_id`,`lead_id`),
  UNIQUE KEY `uq_agent_deal_opportunity` (`opportunity_id`),
  KEY `idx_agent_deal_status` (`workspace_id`,`status`,`created_at`),
  KEY `idx_agent_deal_partner_status` (`partner_id`,`status`,`created_at`),
  KEY `idx_agent_deal_lead_status` (`lead_id`,`status`),
  CONSTRAINT `fk_agent_deal_workspace` FOREIGN KEY (`workspace_id`) REFERENCES `workspaces`(`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_agent_deal_partner` FOREIGN KEY (`partner_id`) REFERENCES `partners`(`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_agent_deal_lead` FOREIGN KEY (`lead_id`) REFERENCES `leads`(`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_agent_deal_opportunity` FOREIGN KEY (`opportunity_id`) REFERENCES `opportunities`(`id`) ON DELETE SET NULL
);

CREATE TABLE `agent_work_evidence` (
  `id` CHAR(36) NOT NULL,
  `workspace_id` CHAR(36) NOT NULL,
  `deal_registration_id` CHAR(36) NOT NULL,
  `partner_id` CHAR(36) NOT NULL,
  `work_type` ENUM('CUSTOMER_INTRODUCTION','NEEDS_DISCOVERY','MEETING','SITE_VISIT','DEMO','NEGOTIATION','PROPOSAL_SUPPORT','FOLLOW_UP','OTHER') NOT NULL,
  `description` TEXT NOT NULL,
  `occurred_at` DATETIME NOT NULL,
  `evidence_reference` VARCHAR(500) NULL,
  `verification_status` ENUM('PENDING','VERIFIED','REJECTED') NOT NULL DEFAULT 'PENDING',
  `verified_by` VARCHAR(190) NULL,
  `verified_at` DATETIME NULL,
  `rejection_reason` TEXT NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_agent_work_deal` (`deal_registration_id`,`occurred_at`),
  KEY `idx_agent_work_partner` (`partner_id`,`verification_status`,`occurred_at`),
  CONSTRAINT `fk_agent_work_workspace` FOREIGN KEY (`workspace_id`) REFERENCES `workspaces`(`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_agent_work_deal` FOREIGN KEY (`deal_registration_id`) REFERENCES `agent_deal_registrations`(`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_agent_work_partner` FOREIGN KEY (`partner_id`) REFERENCES `partners`(`id`) ON DELETE RESTRICT
);